#!/usr/bin/env python3
"""Deterministically adapt the already verified 24 local SVGs to Android VectorDrawable.

No downloads, rasterization, telemetry or new third-party dependency. Symbol paths remain unchanged.
F-Droid's CC-BY-SA-3.0 exception and the other per-icon licenses remain in the durable manifest.
"""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SVG = ROOT / 'preview/public/assets/apps'
DRAWABLE = ROOT / 'android/app/src/main/res/drawable'
JAVA = ROOT / 'android/app/src/main/java/org/oguzdows/mobile/CuratedIcons.java'
A = '{http://schemas.android.com/apk/res/android}'
S = '{http://www.w3.org/2000/svg}'
ET.register_namespace('android', A[1:-1])


def main():
    source = (ROOT / 'preview/src/data.ts').read_text()
    catalog = json.loads(source.split('export const catalog: CatalogApp[] = ', 1)[1].split('];', 1)[0] + ']')
    licenses = {record['id']: record for record in json.loads((SVG / 'manifest.json').read_text())}
    rows, cases = [], []
    for app in catalog:
        name = app['id']
        path = SVG / f'{name}.svg'
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == licenses[name]['sha256']
        svg = ET.fromstring(raw)
        rect, symbol = svg.find(S + 'rect'), svg.find(S + 'path')
        assert symbol.attrib['transform'] == 'translate(14 14) scale(1.5)'
        vector = ET.Element('vector', {A+'width':'48dp', A+'height':'48dp', A+'viewportWidth':'64', A+'viewportHeight':'64'})
        ET.SubElement(vector, 'path', {A+'fillColor':rect.attrib['fill'],
            A+'pathData':'M19,0H45A19,19 0,0 1,64 19V45A19,19 0,0 1,45 64H19A19,19 0,0 1,0 45V19A19,19 0,0 1,19 0Z'})
        group = ET.SubElement(vector, 'group', {A+'translateX':'14', A+'translateY':'14', A+'scaleX':'1.5', A+'scaleY':'1.5'})
        ET.SubElement(group, 'path', {A+'fillColor':symbol.attrib['fill'], A+'pathData':symbol.attrib['d']})
        ET.indent(vector, space='    ')
        output = ET.tostring(vector, encoding='utf-8', xml_declaration=True) + b'\n'
        target = DRAWABLE / f'catalog_{name}.xml'; target.write_bytes(output)
        rows.append({'id':name, 'package':app['package'], 'source_svg':str(path.relative_to(ROOT)),
                     'source_svg_sha256':licenses[name]['sha256'], 'vector_sha256':hashlib.sha256(output).hexdigest(),
                     'license':licenses[name]['license'], 'source':licenses[name]['source'],
                     'modification':'Same symbol path/background/colors, adapted to Android VectorDrawable XML.'})
        cases.append(f'            case "{app["package"]}": return R.drawable.catalog_{name};')
    JAVA.write_text('''package org.oguzdows.mobile;

/** Generated by sync-native-icons.py; per-icon licenses and hashes: android/native-icons.json. */
final class CuratedIcons {
    private CuratedIcons() {}
    static int resource(String packageName) {
        switch (packageName) {
''' + '\n'.join(cases) + '''
            default: return 0;
        }
    }
}
''')
    (ROOT / 'android/native-icons.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
    print(f'{len(rows)} native vectors regenerated from verified SVGs; no new network/icon dependency.')


if __name__ == '__main__':
    main()
